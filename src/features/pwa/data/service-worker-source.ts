export interface ServiceWorkerOptions {
  /** Changes with each deploy so the browser sees a new worker and the update prompt appears. */
  version: string;
  /** Pages and files fetched at install so they exist offline. */
  precache: readonly string[];
}

/** Where a navigation falls back to when the network is down. */
export const OFFLINE_PATH = "/offline";

/** Path prefixes of files whose names change with their content, so they can be served from cache forever. */
export const IMMUTABLE_PREFIXES = ["/_next/static/", "/icons/"] as const;

/**
 * Source of the service worker. Rules:
 * - Navigations always go to the network (pages depend on the session), and only when the network is
 *   down they fall back to the offline page. No page is ever cached, so nobody sees another user's data.
 * - Content-hashed files (`/_next/static/`, `/icons/`) are cache-first.
 * - Everything else (API routes, Firebase and Google requests, non-GET) is not touched.
 * - A new version waits until the user accepts it (`SKIP_WAITING` message) instead of swapping under them.
 */
export function serviceWorkerSource({ version, precache }: ServiceWorkerOptions): string {
  return `// Generated by features/pwa. Do not edit: change service-worker-source.ts.
const VERSION = ${JSON.stringify(version)};
const CACHE_PREFIX = "devfest-";
const CACHE = CACHE_PREFIX + VERSION;
const PRECACHE = ${JSON.stringify(precache)};
const OFFLINE_PATH = ${JSON.stringify(OFFLINE_PATH)};
const IMMUTABLE_PREFIXES = ${JSON.stringify(IMMUTABLE_PREFIXES)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE).map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(navigate(request));
    return;
  }
  if (IMMUTABLE_PREFIXES.some((prefix) => url.pathname.startsWith(prefix))) {
    event.respondWith(cacheFirst(request));
  }
});

async function navigate(request) {
  try {
    return await fetch(request);
  } catch (error) {
    const offline = await caches.match(OFFLINE_PATH);
    return offline || Response.error();
  }
}

async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  const response = await fetch(request);
  if (response.ok && response.type === "basic") {
    const cache = await caches.open(CACHE);
    await cache.put(request, response.clone());
  }
  return response;
}
`;
}
